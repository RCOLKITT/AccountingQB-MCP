#!/usr/bin/env node
/**
 * Generate every tool-documentation artifact from the canonical MCP manifest.
 *
 * Control-plane posture: tool docs are BUILD ARTIFACTS, not prose. The single
 * source of truth is mcpb/manifest.json (itself generated from server.py
 * docstrings by scripts/generate-schemas.py). The one human input is
 * web/src/lib/tools-categories.json — a name→category mapping (data, not prose).
 * Everything else is derived deterministically:
 *
 *   web/src/lib/tools-catalog.json      name + derived short description + write flag
 *   web/src/lib/support-kb/tools.md     the support bot's tool reference, grouped
 *                                       by category, counts computed — never typed
 *
 *   node scripts/generate-tools-catalog.mjs          # write both artifacts
 *   node scripts/generate-tools-catalog.mjs --check  # verify committed == generated (CI)
 *
 * Run after scripts/generate-schemas.py whenever tools change. CI (web-checks)
 * runs --check, so a hand-edit or a skipped regeneration fails the build.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = join(root, "mcpb", "manifest.json");
const CATEGORIES = join(root, "web", "src", "lib", "tools-categories.json");
const OUT_CATALOG = join(root, "web", "src", "lib", "tools-catalog.json");
const OUT_KB = join(root, "web", "src", "lib", "support-kb", "tools.md");

const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
const categories = JSON.parse(readFileSync(CATEGORIES, "utf8"));

/** Deterministic short description: the docstring's first sentence, whitespace
 * collapsed, cut at a word boundary past 160 chars. No hand-written prose. */
function shortDescription(full) {
  const text = (full || "").replace(/\s+/g, " ").trim();
  // First sentence = up to the first ". " (a period followed by space); keep
  // the whole text when it's a single sentence.
  const stop = text.search(/\.\s/);
  let s = stop === -1 ? text : text.slice(0, stop + 1);
  if (s.length > 160) {
    s = s.slice(0, 160).replace(/\s+\S*$/, "") + "…";
  }
  return s;
}

const byName = new Map(
  (manifest.tools || []).map((t) => [
    t.name,
    {
      name: t.name,
      description: shortDescription(t.description),
      // A tool writes to QuickBooks unless it is explicitly annotated read-only.
      write: !(
        (t.annotations || {}).readOnlyHint === true || t.readOnlyHint === true
      ),
    },
  ]),
);

// --- validate the one human input: every tool categorized exactly once -------
const categorized = categories.flatMap((c) => c.tools);
const seen = new Map();
for (const n of categorized) seen.set(n, (seen.get(n) ?? 0) + 1);
const dupes = [...seen].filter(([, c]) => c > 1).map(([n]) => n);
const missing = [...byName.keys()].filter((n) => !seen.has(n));
const unknown = categorized.filter((n) => !byName.has(n));
if (dupes.length || missing.length || unknown.length) {
  console.error(
    `[tool-docs] ✗ tools-categories.json is not a valid 1:1 mapping\n` +
      `  duplicated: ${dupes.join(", ") || "—"}\n` +
      `  uncategorized: ${missing.join(", ") || "—"}\n` +
      `  unknown names: ${unknown.join(", ") || "—"}`,
  );
  process.exit(1);
}

// --- artifact 1: the dashboard catalog ---------------------------------------
const catalog = [...byName.values()].sort((a, b) =>
  a.name.localeCompare(b.name),
);
const catalogOut = JSON.stringify(catalog, null, 2) + "\n";

// --- artifact 2: the support-KB tool reference --------------------------------
const kbLines = [
  "<!-- GENERATED by scripts/generate-tools-catalog.mjs from mcpb/manifest.json",
  "     + tools-categories.json. Do NOT edit by hand — CI --check will fail. -->",
  "",
  `# AccountingQB Tools (${byName.size} Total)`,
  "",
];
for (const cat of categories) {
  kbLines.push(`## ${cat.category} (${cat.tools.length})`);
  kbLines.push("");
  kbLines.push(`${cat.blurb}`);
  kbLines.push("");
  kbLines.push("| Tool | Description |");
  kbLines.push("|------|-------------|");
  for (const name of cat.tools) {
    const t = byName.get(name);
    const d = t.description.replace(/\|/g, "\\|");
    kbLines.push(`| ${name}${t.write ? " ✍️" : ""} | ${d} |`);
  }
  kbLines.push("");
}
kbLines.push("---");
kbLines.push("");
kbLines.push("✍️ = the tool can WRITE to QuickBooks (everything else is read-only).");
kbLines.push("");
kbLines.push("## Usage Examples");
kbLines.push("");
kbLines.push("Ask Claude naturally:");
for (const ex of [
  "What's my P&L for 2025?",
  "Show me all expenses over $500 from last month",
  "Create an expense for $49.99 to GitHub for software subscriptions",
  "Run my Schedule C for tax year 2025",
  "Find any uncategorized transactions",
  "Show the Balance Sheet by Class and find amounts stuck in Not Specified",
  "Move everything unclassed in Work in progress to the Ahous Adventures class",
  "What's my monthly burn rate, and how much runway do I have?",
  "Compare Q1 vs Q2 profit and loss",
  "Find potential duplicate transactions",
  "Generate my 1099 contractor report",
  "Prepare my GST/HST return workpaper for Q2",
  "Run my T2125 summary for this fiscal year",
  "Run a books health audit",
  "Do my month-end close for April",
]) {
  kbLines.push(`- "${ex}"`);
}
kbLines.push("");
const kbOut = kbLines.join("\n");

// --- write or check -----------------------------------------------------------
const artifacts = [
  ["tools-catalog.json", OUT_CATALOG, catalogOut],
  ["support-kb/tools.md", OUT_KB, kbOut],
];

if (process.argv.includes("--check")) {
  let stale = false;
  for (const [label, path, expected] of artifacts) {
    const current = readFileSync(path, "utf8");
    if (current !== expected) {
      console.error(
        `[tool-docs] ✗ ${label} is stale or hand-edited — run \`node scripts/generate-tools-catalog.mjs\``,
      );
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log(`[tool-docs] ✓ all artifacts up to date (${byName.size} tools)`);
} else {
  for (const [label, path, content] of artifacts) {
    writeFileSync(path, content);
    console.log(`[tool-docs] wrote ${label}`);
  }
  const reads = catalog.filter((t) => !t.write).length;
  console.log(
    `[tool-docs] ${byName.size} tools (${reads} read-only, ${byName.size - reads} write)`,
  );
}
